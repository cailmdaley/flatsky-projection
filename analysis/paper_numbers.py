L_HANN = 300.0


def _hann(y, ell, L):
    d = ell - L
    s = np.abs(d) < L_HANN
    w = np.cos(np.pi * d[s] / (2 * L_HANN))**2
    return (w * y[s]).sum() / w.sum()


