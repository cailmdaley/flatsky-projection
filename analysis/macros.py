"""LaTeX macros for the paper's measured numbers, and how they are formatted.

Each numbers output collects its macros in a `Macros` and calls `write`,
which puts `<output_id>.tex` (the `\\newcommand`s `paper/main.tex` inputs) and
`<output_id>.json` (one row per macro: name and value string) under the output directory.
Every macro the code computes is written; whether the prose quotes it is the
paper gate's business, not the writer's.
"""

import json

import numpy as np


def f(x, n=3):
    """A plain fixed-point number."""
    return f"{x:.{n}f}"


def pct(x, n=2):
    """A fraction as a LaTeX percentage."""
    return f"{100 * x:.{n}f}\\%"


def sci(x, n=1):
    """A LaTeX scientific-notation number, e.g. 6.4\\times10^{-8}."""
    if x == 0 or not np.isfinite(x):
        return "0"
    e = int(np.floor(np.log10(abs(x))))
    m = x / 10.0 ** e
    return rf"{m:.{n}f}\times10^{{{e}}}"


WORDS = {2: "two", 3: "three", 4: "four", 5: "five", 6: "six", 7: "seven",
         8: "eight", 9: "nine", 10: "ten"}


def rng(lo, hi, n=2):
    """A range, as the paper writes them."""
    return f"${f(lo, n)}$--${f(hi, n)}$"


class Macros(dict):
    def add(self, name, value):
        if name in self:
            raise KeyError(f"duplicate macro {name}")
        self[name] = value

    def tex(self, output_id):
        head = (f"% Generated by the `{output_id}` output of astra.yaml -- do not edit.\n"
                "% Every measured number quoted in the paper lives in these files.\n")
        return head + "".join(f"\\newcommand{{\\{k}}}{{{v}}}\n" for k, v in self.items())

    def write(self, out, output_id):
        """Write `<output_id>.tex` and `<output_id>.json` under `out`."""
        if not all(name.isalpha() for name in self):
            raise ValueError("LaTeX control sequences must be alphabetic")
        out.mkdir(parents=True, exist_ok=True)
        (out / f"{output_id}.tex").write_text(self.tex(output_id))
        rows = [{"macro": k, "value": v} for k, v in self.items()]
        (out / f"{output_id}.json").write_text(json.dumps(rows, indent=2) + "\n")
        print(f"wrote {out / output_id}.tex  ({len(self)} macros)")
